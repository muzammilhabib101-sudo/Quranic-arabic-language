// Writes content/draft/review-report.md (npm run review-report): every lesson
// with its format, review status, source slides, and anything that needs a
// look — words not covered, missing English, exercises without an answer.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { checkLesson } from "./check-arabic.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (...p) => JSON.parse(readFileSync(join(ROOT, ...p), "utf8"));
const pad = (n) => String(n).padStart(3, "0");

const map = read("content", "course-map.json");

/** Every Text field ({ur, en?}) in a lesson, with its path. */
function texts(node, path = "") {
  if (!node || typeof node !== "object") return [];
  if (typeof node.ur === "string" && Object.keys(node).every((k) => k === "ur" || k === "en")) {
    return [{ path, text: node }];
  }
  return Object.entries(node).flatMap(([k, v]) => texts(v, path ? `${path}.${k}` : k));
}

const rows = [];
const notes = [];
const examples = [];
for (const l of map.lessons) {
  const file = join(ROOT, "content", "lessons", `${l.id}.json`);
  const slides = `${l.sourceSlides.from}–${l.sourceSlides.to}`;
  if (!existsSync(file)) {
    rows.push(`| ${l.id} | ${l.title.en} | slides | — | ${slides} | |`);
    continue;
  }
  const c = read("content", "lessons", `${l.id}.json`);
  const verseWords = read("content", "quran", "words", `${pad(c.verse.surah)}.json`)[c.verse.ayah].w;
  const covered = new Set(c.words.map((w) => w.position));
  const missingWords = verseWords.filter((w) => !covered.has(w.p)).map((w) => w.p);
  const noEnglish = texts(c).filter((x) => !x.text.en).map((x) => x.path);
  const issues = [];
  if (missingWords.length) issues.push(`words not explained: ${missingWords.join(", ")}`);
  if (noEnglish.length) issues.push(`${noEnglish.length} texts without English`);
  c.check.forEach((q) => q.answer >= q.options.length && issues.push(`${q.id}: answer out of range`));
  const arabic = checkLesson(c);
  if (arabic.mismatches.length) {
    issues.push(`${arabic.mismatches.length} quoted words differ from the verse (npm run check-arabic)`);
  }
  if (arabic.unmatched.length) {
    examples.push(`- **${l.id}** (${arabic.checked} verse words checked automatically): ${arabic.unmatched.join(" ")}`);
  }
  rows.push(
    `| ${l.id} | ${l.title.en} | text | **${c.status}**${c.reviewedBy ? ` (${c.reviewedBy})` : ""} | ${slides} | ${issues.join("; ") || "—"} |`,
  );
  if (noEnglish.length) notes.push(`- ${l.id}: English missing in ${noEnglish.join(", ")}`);
}

const text = map.lessons.filter((l) => existsSync(join(ROOT, "content", "lessons", `${l.id}.json`)));
const md = `# Lesson review report

Generated by \`npm run review-report\`. ${text.length} of ${map.lessons.length} lessons are text lessons; the rest are shown as slides.
A text lesson stays **draft** (with the badge on the site) until a teacher checks it against its slides on \`/ur/review/<id>/\` and sets \`"status": "reviewed"\`.

| Lesson | Title | Format | Status | Slides | Needs a look |
|---|---|---|---|---|---|
${rows.join("\n")}
${notes.length ? `\n## Missing English\n\n${notes.join("\n")}\n` : ""}
## Arabic to check by eye

Words quoted from a lesson's own verse are compared with the verified text automatically (\`npm run check-arabic\`, which also runs before every build). The words below — grammar examples, patterns and word parts — are not from the verse, so a teacher should check their vowels by eye:

${examples.join("\n")}
`;

writeFileSync(join(ROOT, "content", "draft", "review-report.md"), md);
console.log(`${text.length} text lessons, ${map.lessons.length - text.length} slide lessons → content/draft/review-report.md`);
